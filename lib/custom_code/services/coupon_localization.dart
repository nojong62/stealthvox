  /// 지급된 초 → "2시간", "30분" 같은 짧은 표시.
  String duration(int seconds) {
    if (seconds >= 3600 && seconds % 3600 == 0) {
      return this['hours'].replaceAll('{n}', '${seconds ~/ 3600}');
    }
    if (seconds >= 3600) {
      return this['hours'].replaceAll('{n}', (seconds / 3600).toStringAsFixed(1));
    }
    return this['minutes'].replaceAll('{n}', '${(seconds / 60).round()}');
  }
