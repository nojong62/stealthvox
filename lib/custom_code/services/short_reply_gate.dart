// 🗣️ [SHORT-REPLY] "네."는 환청이 아니라 대답일 수 있다 — 소리 난 시간이 가른다
// --------------------------------------------------------------------
// 서클톡·시나리오톡의 잡음 게이트는 '네'·'응'·한 글자 전사를 환청 목록으로
// 막는다. 그 목록은 무음 구간·AI 목소리 꼬리에서 전사 모델이 지어내는 글자를
// 잡으려고 생겼고, 그래서 목록에서 빼는 것만으로는 못 고친다(2026-08-06 메모).
//
// 2026-09-16 시나리오톡 실기기:
//   AI  "혹시 새로 산소통을 하나 사야 하냐는 말씀이세요?"
//   유저 "네."  voicedMs=1260  → noise_transcript로 폐기 → 유저가 다시 말함
//
// 서버 VAD가 잰 **소리 난 시간**이 있다. 듀오가 같은 문제를 이 값으로 풀었다
// (`kDuoMinVoicedMs`). 1.26초 동안 실제로 소리가 났으면 그건 사람 말이다.
//
// 규칙(실장님 확정): 환청 목록은 그대로 두고, `voicedMs`가 충분하면 살린다.
// 문턱은 800ms에서 출발한다 — 이 두 모드의 환청이 몇 ms로 오는지는 아직
// 실측이 없다. `[NOISE-GATE]` 줄에 voicedMs를 같이 남겨 다음 판들에서 잰다.
// 값을 못 쟀으면(null) 예전대로 목록이 이긴다.
// ====================================================================

/// 이보다 오래 소리가 났으면 짧은 전사도 대답으로 본다.
const int kShortReplyMinVoicedMs = 800;

/// 잡음 목록에 걸린 전사를 **소리 난 시간으로 되살릴 것인가.**
bool shortReplyRescuedByVoice(int? voicedMs,
        {int minMs = kShortReplyMinVoicedMs}) =>
    voicedMs != null && voicedMs >= minMs;
